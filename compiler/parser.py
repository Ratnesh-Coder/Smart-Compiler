"""Syntax analysis driver built on PLY Yacc (``ply.yacc``).

The LALR(1) tables are generated by PLY from :class:`compiler.grammar.CGrammar`. This module adds
the error handling strategy used by the whole project:

1. **Token-insertion repair (preferred).** When the parser fails on token *T* and the parser
   tables say that ``;``, ``)``, ``]`` or (at end of file) ``}`` would be acceptable here, the
   missing token is virtually inserted before *T* and parsing continues with the *complete*
   program structure. This yields one precise diagnostic per real mistake and keeps the AST
   usable, which avoids cascades of misleading follow-up errors.
2. **Rollback.** A repair is only committed as a diagnostic if the parser makes progress after
   it. If the parser fails again on the very same token, the repair is discarded and a generic
   "unexpected token" diagnostic is reported instead.
3. **Panic mode.** Otherwise PLY's own recovery runs through the ``error SEMI`` productions;
   PLY suppresses further reports until three tokens have been shifted successfully.
"""
from __future__ import annotations

from collections import deque
from dataclasses import dataclass, field
from typing import Any, Optional

try:
    from ply import yacc
except ImportError as exc:  # pragma: no cover - exercised only when PLY is missing
    raise ImportError("PLY is required for syntax analysis. Install it with: pip install ply") from exc

from compiler.ast_nodes import ProgramNode
from compiler.error_classifier import SyntaxClassification, classify_syntax_error
from compiler.error_manager import ErrorManager
from compiler.grammar import CGrammar
from compiler.tokens import LEXEME_BY_TYPE, Token
from utils.source_location import LineIndex

MAX_REPAIRS = 50
_REPAIR_RANK = {"RPAREN": 0, "RBRACKET": 0, "SEMI": 1, "LBRACE": 1, "RBRACE": 2}
_REPAIR_ORDER = ("RPAREN", "RBRACKET", "SEMI", "RBRACE")


@dataclass
class ParseResult:
    """Outcome of :meth:`CParser.parse`."""

    ast: Optional[ProgramNode]
    repairs: int = 0
    panic_recovery: bool = False
    ast_reliable: bool = False
    notes: list[str] = field(default_factory=list)


class TokenStream:
    """Adapter that feeds a pre-computed token list to PLY and supports token insertion."""

    def __init__(self, tokens: list[Token]) -> None:
        self._tokens = list(tokens)
        self._pos = 0
        self._queue: deque[Token] = deque()
        self.history: list[Token] = []
        self.open_braces = 0
        self.total_brace_balance = sum(1 if t.type == "LBRACE" else -1 if t.type == "RBRACE" else 0
                                       for t in self._tokens)

    # PLY lexer protocol -------------------------------------------------------------
    def input(self, data: Any) -> None:  # noqa: A003 - PLY lexer interface
        """No-op: the token list is supplied at construction time."""

    def token(self) -> Optional[Token]:
        if self._queue:
            tok = self._queue.popleft()
        elif self._pos < len(self._tokens):
            tok = self._tokens[self._pos]
            self._pos += 1
        else:
            return None
        self.history.append(tok)
        self._track(tok, +1)
        return tok

    # repair support -----------------------------------------------------------------
    def _track(self, tok: Token, sign: int) -> None:
        if tok.type == "LBRACE":
            self.open_braces += sign
        elif tok.type == "RBRACE":
            self.open_braces -= sign

    def previous_of(self, tok: Optional[Token]) -> Optional[Token]:
        h = self.history
        if tok is None:
            return h[-1] if h else None
        for i in range(len(h) - 1, -1, -1):
            if h[i] is tok:
                return h[i - 1] if i > 0 else None
        return None

    def insert_before(self, tok: Optional[Token], synthetic: Token) -> None:
        """Deliver ``synthetic`` before ``tok`` (the last token handed out; ``None`` at end of file)."""
        if tok is not None:
            if self.history and self.history[-1] is tok:
                self.history.pop()
                self._track(tok, -1)
            self._queue.appendleft(tok)
        self._queue.appendleft(synthetic)

    def append_at_eof(self, tokens: list[Token]) -> None:
        self._queue.extend(tokens)


@dataclass
class _PendingRepair:
    key: int
    rank: int
    classification: SyntaxClassification
    line: int
    column: int
    offset: int
    context: dict[str, Any]


class CParser:
    """PLY-based parser with repair/recovery for the supported C subset."""

    def __init__(self) -> None:
        self._grammar = CGrammar()
        self._grammar.error_handler = self._on_error
        self._parser = yacc.yacc(module=self._grammar, start="translation_unit", debug=False,
                                 write_tables=False)
        self._stream: Optional[TokenStream] = None
        self._errors: Optional[ErrorManager] = None
        self._index = LineIndex("")
        self._pending: Optional[_PendingRepair] = None
        self._repairs = 0
        self._panic = False

    # ------------------------------------------------------------------ public API
    def parse(self, tokens: list[Token], source: str, errors: ErrorManager) -> ParseResult:
        """Parse ``tokens``; syntax diagnostics are reported to ``errors``."""
        self._errors = errors
        self._index = LineIndex(source)
        self._stream = TokenStream(tokens)
        self._pending = None
        self._repairs = 0
        self._panic = False
        self._grammar.reset(errors)

        tree = self._parser.parse(lexer=self._stream, tokenfunc=self._stream.token)
        self._commit_pending()

        ast = tree if isinstance(tree, ProgramNode) else None
        panic = self._panic or self._grammar.recovered
        reliable = ast is not None and not panic and self._grammar.action_errors == 0
        notes: list[str] = []
        if self._repairs:
            notes.append(f"{self._repairs} missing token(s) were virtually inserted to continue parsing.")
        if panic:
            notes.append("Panic-mode recovery discarded tokens; the syntax tree is incomplete.")
        return ParseResult(ast=ast, repairs=self._repairs, panic_recovery=panic,
                           ast_reliable=reliable, notes=notes)

    # ------------------------------------------------------------------ PLY error hook
    def _on_error(self, tok: Optional[Token]) -> Optional[Token]:
        stream = self._stream
        assert stream is not None and self._errors is not None
        expected = self._expected_terminals()
        key = tok.offset if tok is not None else -1
        prev = stream.previous_of(tok)

        pending = self._pending
        if pending is not None and pending.key != key:
            self._commit_pending()
            pending = None

        repair = self._choose_repair(tok, prev, expected, pending)
        if repair is not None and self._repairs < MAX_REPAIRS:
            if pending is not None:
                self._commit_pending()  # the parser consumed the earlier insertion: it was right
            self._begin_repair(tok, prev, expected, repair)
            self._parser.errok()
            return None

        if pending is not None:
            self._pending = None  # rollback: the insertion did not help
        self._report_panic(tok, prev, expected)
        self._panic = True
        return None

    # ------------------------------------------------------------------ table simulation
    def _simulate(self, terminals: list[str]) -> bool:
        """Would the LALR automaton accept ``terminals`` in order from its *current* stack?

        Works on a copy of PLY's state stack using the generated ``action``/``goto`` tables, so it
        follows exactly the reductions the real parse would perform (LALR lookaheads are merged
        across contexts, which is why the raw ``action[state]`` keys alone over-approximate).
        """
        parser = self._parser
        try:
            stack = list(parser.statestack)
            actions, goto, prods, dflt = parser.action, parser.goto, parser.productions, parser.defaulted_states
        except AttributeError:
            return False
        for term in terminals:
            for _ in range(10_000):  # bound the reduce chain defensively
                state = stack[-1]
                act = dflt.get(state) if state in dflt else actions.get(state, {}).get(term)
                if act is None:
                    return False
                if act > 0:
                    stack.append(act)
                    break
                if act == 0:
                    return True
                prod = prods[-act]
                if prod.len:
                    del stack[-prod.len:]
                stack.append(goto[stack[-1]][prod.name])
            else:
                return False
        return True

    def _expected_terminals(self) -> list[str]:
        """Terminals the parser could really accept next (precise, via table simulation)."""
        try:
            state = self._parser.statestack[-1]
            candidates = [t for t in self._parser.action.get(state, {}) if t not in ("error", "$end")]
        except (AttributeError, IndexError, KeyError):
            return []
        return sorted(t for t in candidates if self._simulate([t]))

    # ------------------------------------------------------------------ repair logic
    def _choose_repair(self, tok: Optional[Token], prev: Optional[Token], expected: list[str],
                       pending: Optional[_PendingRepair]) -> Optional[str]:
        stream = self._stream
        assert stream is not None
        if prev is None:
            return None
        at_eof = tok is None
        if pending is not None and not (at_eof or tok.type == "RBRACE"):
            return None  # an ordinary token receives at most one insertion
        last_rank = pending.rank if pending is not None else -1
        exp = set(expected) - {"$end"}

        # After a function header only '{' (definition) or ';' (prototype) are possible.
        if exp == {"LBRACE", "SEMI"}:
            if stream.total_brace_balance < 0 and _REPAIR_RANK["LBRACE"] > last_rank:
                return "LBRACE"
            return "SEMI" if _REPAIR_RANK["SEMI"] > last_rank else None
        follow = [] if tok is None else [tok.type]

        for tt in _REPAIR_ORDER:
            if tt not in exp or _REPAIR_RANK[tt] <= last_rank:
                continue
            if tt == "SEMI":
                if prev.type in ("SEMI", "LBRACE", "RBRACE"):
                    continue
                if tok is not None and tok.type == "ID" and prev.type == "ID" and prev.line == tok.line:
                    continue  # "itn x" - two adjacent identifiers are more likely a misspelt keyword
            if tt == "RBRACE" and (not at_eof or stream.open_braces <= 0):
                continue
            if self._simulate([tt] + follow):  # the insertion must let the parser consume the offending token
                return tt
        return None

    def _begin_repair(self, tok: Optional[Token], prev: Token, expected: list[str], tt: str) -> None:
        stream = self._stream
        assert stream is not None
        pos = prev.end_offset
        line, col = self._index.locate(pos)
        lexeme = LEXEME_BY_TYPE[tt]
        count = 1
        if tt == "RBRACE":
            count = max(stream.open_braces, 1)
            stream.append_at_eof([Token("RBRACE", "}", line, col, pos, 0, synthetic=True)
                                  for _ in range(count)])
        else:
            stream.insert_before(tok, Token(tt, lexeme, line, col, pos, 0, synthetic=True))
        cls = classify_syntax_error(tok, prev, expected, repair=tt, missing_count=count)
        ctx = dict(cls.context)
        ctx.update(insert_offset=pos, insert_text=lexeme, repair_token=tt, missing_count=count,
                   token_type=tok.type if tok else "$end", token_offset=tok.offset if tok else -1,
                   prev_type=prev.type, prev_lexeme=prev.value, prev_offset=prev.offset,
                   prev_line=prev.line)
        key = tok.offset if tok is not None else -1
        self._pending = _PendingRepair(key, _REPAIR_RANK[tt], cls, line, col, pos, ctx)
        self._repairs += 1

    def _commit_pending(self) -> None:
        p, self._pending = self._pending, None
        if p is None or self._errors is None:
            return
        self._errors.report(p.classification.kind, p.line, p.column, message=p.classification.message,
                            description=p.classification.description,
                            suggestion=p.classification.suggestion, offset=p.offset, length=0,
                            context=p.context)

    def _report_panic(self, tok: Optional[Token], prev: Optional[Token], expected: list[str]) -> None:
        assert self._errors is not None
        cls = classify_syntax_error(tok, prev, expected)
        pos = tok.offset if tok is not None else (prev.end_offset if prev is not None else 0)
        line, col = self._index.locate(pos)
        ctx = dict(cls.context)
        ctx.update(token_type=tok.type if tok else "$end", token_lexeme=tok.value if tok else "",
                   token_offset=pos, prev_type=prev.type if prev else None,
                   prev_lexeme=prev.value if prev else "", prev_offset=prev.offset if prev else -1,
                   prev_end=prev.end_offset if prev else -1)
        self._errors.report(cls.kind, line, col, message=cls.message, description=cls.description,
                            suggestion=cls.suggestion, offset=pos,
                            length=tok.length if tok is not None else 0, context=ctx)
